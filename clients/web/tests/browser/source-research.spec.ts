import { test, expect } from '@playwright/test'
import { configureNotebookModel, pairNotebook, createSpace } from './notebook-fixture'

test('智能搜集需求、真实进度恢复、双结果勾选与确认导入，停止后不再调用模型', async ({ page }) => {
  test.setTimeout(150_000)
  await configureNotebookModel(page)
  await pairNotebook(page, 'learner')
  const space = await createSpace(page, '智能搜集 R-A 浏览器验收')
  await page.goto(`/app/spaces/${space.id}?panel=sources`)
  await page.getByRole('button', { name: '＋ 添加来源', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '添加来源', exact: true })
  await dialog.getByRole('button', { name: '智能搜集', exact: true }).click()
  await dialog.getByLabel('想找什么资料？', { exact: true }).fill('寻找协议的基础和练习资料')
  await dialog.getByRole('button', { name: '开始搜集', exact: true }).click()
  await expect(dialog.getByText(/当前搜索词：/)).toBeVisible({ timeout: 30_000 })
  await page.reload()
  await page.getByRole('button', { name: '＋ 添加来源', exact: true }).click()
  await dialog.getByRole('button', { name: '智能搜集', exact: true }).click()
  const first = dialog.getByRole('checkbox', { name: '选择候选：搜集验收基础', exact: true })
  const second = dialog.getByRole('checkbox', { name: '选择候选：搜集验收练习', exact: true })
  await expect(first).toBeChecked({ timeout: 90_000 })
  await expect(second).toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: '将整理报告也加入来源', exact: true })).not.toBeChecked()
  await dialog.getByText('整理报告', { exact: true }).click()
  await expect(dialog.getByText('资料提供协议的基础说明。[section-1:1]', { exact: true })).toBeVisible()
  await second.uncheck()
  await expect(second).not.toBeChecked()
  await dialog.getByRole('button', { name: '查看导入预览', exact: true }).click()
  await expect(dialog.getByRole('region', { name: '确认导入预览' })).toBeVisible()
  await dialog.getByRole('button', { name: '确认导入', exact: true }).click()
  await expect(dialog.getByText('已导入所选来源。', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭添加来源', exact: true }).click()
  await expect(page.locator('.notebook-sources-list').getByRole('button', { name: '打开来源：搜集验收基础', exact: true })).toBeVisible()
  await expect(page.locator('.notebook-sources-list').getByRole('button', { name: '打开来源：搜集验收练习', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /^选择来源：搜集验收基础/ })).not.toBeChecked()
  await page.getByRole('button', { name: '＋ 添加来源', exact: true }).click()
  await dialog.getByRole('button', { name: '智能搜集', exact: true }).click()
  await dialog.getByLabel('想找什么资料？', { exact: true }).fill('停止验证：寻找协议练习')
  await dialog.getByRole('button', { name: '开始搜集', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '停止搜集', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '停止搜集', exact: true }).click()
  await expect(dialog.getByText(/已停止，结果未完成/)).toBeVisible()
  const stats = await (await page.request.get('http://127.0.0.1:32930/stats')).json()
  await page.waitForTimeout(1500)
  const after = await (await page.request.get('http://127.0.0.1:32930/stats')).json()
  expect(after.calls).toBe(stats.calls)
})
